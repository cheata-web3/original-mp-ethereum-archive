// Verify archived data, not live balances. No RPC, wallet, or private key.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const json = p => JSON.parse(read(p));
const m = json('archive/ethereum-mainnet.json');
const x = json('archive/rpc-reads.json');
const tx = json('archive/creation-transaction.json');
const receipt = json('archive/creation-receipt.json');
const block = json('archive/block.json');
const args = json('verification/etherscan-source-match/decoded-constructor-args.json');
const lower = x => x.toLowerCase();
assert.equal(m.chainId, 1);
assert.equal(lower(m.contractAddress), '0x5c5cea5f9466d8fd9b8d9b3bd0f4705fc4a7ae74');
assert.equal(lower(m.creator), '0x102eee422113140fbdc2544f495a947399ab100b');
assert.deepEqual(x, m.readValues);
assert.equal(x.name, 'MP');
assert.equal(x.symbol, 'MP');
assert.equal(x.decimals, 8);
assert.equal(x.decimals, args._decimalUnits);
assert.equal(x.totalSupplyRaw, '1000000000000000000');
assert.equal(x.totalSupplyRaw, args._initialAmount);
assert.equal(x.creatorBalanceRaw, x.totalSupplyRaw);
assert.equal(BigInt(x.totalSupplyRaw) / (10n ** BigInt(x.decimals)), 10000000000n);
assert.equal(lower(tx.from), lower(m.creator));
assert.equal(tx.to, null);
assert.equal(tx.hash, m.creationTransaction);
assert.equal(tx.input.toLowerCase(), read('archive/creation-input.hex').trim().toLowerCase());
assert.equal(receipt.transactionHash, tx.hash);
assert.equal(receipt.status, '0x1');
assert.equal(lower(receipt.contractAddress), lower(m.contractAddress));
assert.equal(lower(receipt.from), lower(m.creator));
assert.equal(Number(receipt.blockNumber), m.creationBlock);
assert.equal(Number(tx.blockNumber), m.creationBlock);
assert.equal(Number(block.number), m.creationBlock);
assert.equal(block.hash, receipt.blockHash);
assert.equal(block.hash, tx.blockHash);
assert.equal(Number(block.timestamp) * 1000, Date.parse(m.creationTimestampUtc));
assert.match(read('README.md'), /\| Decimals \| `8` \|/);
assert.match(read('PROVENANCE.md'), /decimals: 8/);
console.log('PASS: archived identity, creation data, supply, decimals, and documentation agree.');
console.log('This checks captured evidence; it does not establish current wallet control.');
